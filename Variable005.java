public class Variable005 {
    public static void main(String[] args) {
        // Deklarasi variabel
        double num1, num2;

        // Isi variable
        num1 = 69;
        num2 = 67;

        // Cetak variable
        System.out.println("Angka 1 = " + num1);
        System.out.println("Angka 2 = " + num2);
        System.out.println("Hasil:");
        System.out.println("(+) " + (num1 + num2));
        System.out.println("(-) " + (num1 - num2));
        System.out.println("(*) " + (num1 * num2));
        System.out.println("(/) " + (num1 / num2));
    }
}
